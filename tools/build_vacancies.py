NS = 'http://www.sitemaps.org/schemas/sitemap/0.9'
KYIV = ZoneInfo('Europe/Kyiv')


def require(condition, message):
    if not condition:
        raise ValueError(message)


def valid_text(value, limit):
    return isinstance(value, str) and 0 < len(value) <= limit and value == value.strip() and not any(ord(c) < 32 for c in value)


def valid_amount(value):
    return type(value) in (int, float) and 0 < value <= 100_000_000 and round(value, 2) == value


def https_url(value):
    if not isinstance(value, str) or not value or re.search(r'[\s\\\x00-\x1f\x7f]', value):
        return False
    parsed = urlsplit(value)
    return parsed.scheme == 'https' and bool(parsed.hostname) and not parsed.username and not parsed.password and parsed.port in (None, 443)


def valid_date(value):
    return isinstance(value, str) and re.fullmatch(r'\d{4}-\d{2}-\d{2}', value) and date.fromisoformat(value)


def work_modes(job):
    return job['modes'] if job['status'] == 'external' else [job['mode']]


def listing_date(job):
    return job['sourceChecked'] if job['status'] == 'external' else job['datePosted']


def read_jobs(source):
    jobs = json.loads(source.read_text(encoding='utf-8'))
    require(isinstance(jobs, list), 'Expected an array of vacancies')
    seen = set()
    for job in jobs:
        require(isinstance(job, dict), 'Expected a vacancy object')
        job_id = job.get('id', '')
        require(isinstance(job_id, str) and re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', job_id)
                and len(job_id) <= 72 and not job_id.startswith(('demo-', 'local-')), 'Invalid or reserved vacancy id')
        require(job_id not in seen, f'{job_id}: duplicate id')
        seen.add(job_id)
        status = job.get('status')
        require(status in ('draft', 'published', 'closed', 'external'), f'{job_id}: invalid status')
        if status == 'draft':
            continue
        require(valid_text(job.get('company'), 120), f'{job_id}: company is required')
        for field, choices in [('sector', SECTORS), ('employment', TERMS)]:
            require(job.get(field) in choices, f'{job_id}: invalid {field}')
        if status == 'external':
            require(https_url(job.get('sourceUrl')) and https_url(job.get('applyUrl')),
                    f'{job_id}: employer source and application links must use HTTPS')
            require(valid_date(job.get('sourceChecked')), f'{job_id}: invalid source check date')
            modes = job.get('modes')
            require(isinstance(modes, list) and modes and all(mode in MODES for mode in modes)
                    and len(set(modes)) == len(modes), f'{job_id}: invalid work modes')
        else:
            require(job.get('employerApproved') is True and job.get('feeAgreed') is True,
                    f'{job_id}: confirm employer permission and a recruitment fee agreement before listing')
            require(job.get('mode') in MODES, f'{job_id}: invalid mode')
            country = job.get('country', '')
            require(isinstance(country, str) and re.fullmatch(r'[A-Z]{2}', country), f'{job_id}: country must be an ISO two-letter code')
            for field in ('datePosted', 'validThrough'):
                require(valid_date(job.get(field)), f'{job_id}: invalid {field}')
            require(job['validThrough'] >= job['datePosted'], f'{job_id}: deadline precedes publication')
            require(job.get('applyUrl') in (None, '') or https_url(job['applyUrl']), f'{job_id}: invalid HTTPS application URL')
        salary = job.get('salary')
        if salary is not None:
            require(isinstance(salary, dict) and valid_amount(salary.get('min')) and valid_amount(salary.get('max'))
                    and salary['min'] <= salary['max']
                    and salary.get('currency') in ('UAH', 'EUR', 'USD', 'PLN', 'GBP', 'CAD', 'CHF', 'CZK')
                    and salary.get('unit') in ('MONTH', 'HOUR') and type(salary.get('gross')) is bool, f'{job_id}: invalid salary range')
        for lang in LOCALES:
            copy = job.get(lang)
            if lang != 'uk' and copy is None:
                continue
            require(isinstance(copy, dict), f'{job_id}: {lang} content is required')
            for field, limit in STRINGS.items():
                require(valid_text(copy.get(field), limit), f'{job_id}: invalid {lang}.{field}')
            if 'payNote' in copy:
                require(valid_text(copy['payNote'], 160), f'{job_id}: invalid {lang}.payNote')
            for field in LISTS:
                items = copy.get(field)
                require(isinstance(items, list) and 1 <= len(items) <= 10 and all(valid_text(item, 300) for item in items),
                        f'{job_id}: invalid {lang}.{field}')
    return jobs


def localized(items):
    return {key: {'uk': labels[0], 'en': labels[1], 'ru': RUSSIAN[labels[1]]} for key, labels in items.items()}


def json_html(value):
    return json.dumps(value, ensure_ascii=False).replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')


def locale_path(lang):
    return '' if lang == 'uk' else lang + '/'


def write_page(path, html):
    if path.is_file():
        require(MARKER in path.read_text(encoding='utf-8'), f'Refusing to overwrite a manually maintained page: {path}')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(html, encoding='utf-8')


def translator(lang):
    def translate(uk, en):
        if lang == 'ru':
            return RUSSIAN[en]
        return en if lang == 'en' else uk
    return translate


def page_shell(lang, route, title, description, body, *, languages=LOCALES, schema=None, noindex=False):
    crumb = translator(lang)('Вакансії', 'Vacancies')
    return page(lang, route.removeprefix(locale_path(lang)), title, description, body,
                languages=languages, schemas=(schema,) if schema else (), noindex=noindex,
                crumbs=((crumb, 'jobs/'),), modules=('jobs.mjs',), marker=MARKER)


def vacancy_page(job, lang, active):
    t = translator(lang)
    copy = job[lang]
    external = job['status'] == 'external'
    salary = job.get('salary')
    pay = escape(copy.get('payNote') or t('Оплату не вказано', 'Salary not disclosed'))
    if salary:
        low, high = salary['min'], salary['max']
        format_amount = lambda amount: f'{amount:,.2f}'.rstrip('0').rstrip('.').replace(',', ' ')
        numbers = format_amount(low) if low == high else f'{format_amount(low)}–{format_amount(high)}'
        if lang != 'en':
            numbers = numbers.replace('.', ',')
        unit = t('місяць', 'month') if salary['unit'] == 'MONTH' else t('година', 'hour')
        taxes = t('до податків', 'gross') if salary['gross'] else t('після податків', 'net')
        pay = f"{numbers} {salary['currency']} / {unit}, {taxes}"
    employment = t(*TERMS[job['employment']])
    mode = ' / '.join(t(*MODES[key]) for key in work_modes(job))
    sections = ''.join(
        f'<section class="seo-section"><h2>{label}</h2><ul>' + ''.join(f'<li>{escape(item)}</li>' for item in copy[key]) + '</ul></section>'
        for key, label in [('duties', t('Обов’язки','Responsibilities')), ('requirements', t('Вимоги','Requirements')), ('conditions', t('Умови','Conditions'))]
    )
    apply_url = job.get('applyUrl') or ('../../apply/?vacancy=' + quote(job['id']))
    recipient = t('Форма роботодавця відкриється за посиланням.', 'The link opens the employer’s application form.') if job.get('applyUrl') else {
        'uk': 'Резюме отримає команда Emplivo.',
        'en': 'Emplivo will receive your CV.',
        'ru': 'Резюме получит команда Emplivo.',
    }[lang]
    closed = t('Прийом відгуків завершено.', 'Applications are closed.')
    source_label = ''
    location = escape(copy['location'])
    if external:
        source_label = t('Оголошення роботодавця', 'Employer listing')
        dates = f'<dt>{t("Джерело переглянуто","Source checked")}</dt><dd><time datetime="{job["sourceChecked"]}">{job["sourceChecked"]}</time></dd>'
        apply = f'''<p>{t('Відгук і відбір проводить роботодавець.', 'The employer handles applications and selection.')}</p>
<a class="button primary" href="{escape(apply_url)}" data-employer-apply>{t('Відгукнутися на сайті роботодавця','Apply on the employer’s site')}</a>
<p><a href="{escape(job['sourceUrl'])}" data-vacancy-source>{t('Оригінал оголошення','Original job brief')}</a></p>'''
    else:
        location += ' · ' + job['country']
        dates = f'''<dt>{t('Подано','Posted')}</dt><dd><time datetime="{job['datePosted']}">{job['datePosted']}</time></dd>
<dt>{t('Відгуки до','Apply by')}</dt><dd><time datetime="{job['validThrough']}">{job['validThrough']}</time></dd>'''
        apply = (f'<div data-vacancy-until="{job["validThrough"]}"><a class="button primary" href="{escape(apply_url)}">{t("Відгукнутися","Apply")}</a><p>{recipient}</p></div>'
                 f'<p data-vacancy-expired hidden>{closed}</p>') if active else f'<p>{closed}</p>'
    body = f'''<div class="seo-hero">
<p class="eyebrow">{escape(t(*SECTORS[job['sector']]))}{' · ' + source_label if source_label else ''}</p>
<h1>{escape(copy['title'])}</h1><p class="seo-lead">{escape(job['company'])} · {escape(copy['location'])}</p>
<p>{escape(copy['summary'])}</p></div>
<div class="seo-columns"><div>{sections}</div>
<aside class="seo-aside"><h2>{t('Деталі вакансії','Vacancy details')}</h2>
<dl class="vacancy-facts"><dt>{t('Місце роботи','Location')}</dt><dd>{location}</dd>
<dt>{t('Формат і зайнятість','Work arrangement and employment')}</dt><dd>{mode} · {employment}</dd>
<dt>{t('Оплата','Pay')}</dt><dd>{pay}</dd><dt>{t('Графік','Schedule')}</dt><dd>{escape(copy['schedule'])}</dd>
{dates}</dl>
{apply}</aside></div>'''
    schema = None
    if active and not external:
        schema = {
            '@context': 'https://schema.org', '@type': 'JobPosting', 'title': copy['title'],
            'description': f'<p>{escape(copy["summary"])}</p>{sections}<p>{escape(copy["schedule"])}</p>',
            'identifier': {'@type': 'PropertyValue', 'name': 'Emplivo', 'value': job['id']},
            'hiringOrganization': {'@type': 'Organization', 'name': job['company']},
            'datePosted': job['datePosted'],
            'validThrough': datetime.combine(date.fromisoformat(job['validThrough']), time(23, 59, 59), KYIV).isoformat(),
            'employmentType': job['employment'], 'inLanguage': lang,
        }
        if work_modes(job) == ['remote']:
            schema['jobLocationType'] = 'TELECOMMUTE'
            schema['applicantLocationRequirements'] = {'@type': 'Country', 'name': job['country']}
        else:
            schema['jobLocation'] = {'@type': 'Place', 'address': {
                '@type': 'PostalAddress', 'addressLocality': copy['location'], 'addressCountry': job['country']}}
        if salary and salary['gross']:
            amount = {'value': low} if low == high else {'minValue': low, 'maxValue': high}
            schema['baseSalary'] = {'@type': 'MonetaryAmount', 'currency': salary['currency'],
                                    'value': {'@type': 'QuantitativeValue', **amount, 'unitText': salary['unit']}}
    return page_shell(lang, locale_path(lang) + f"vacancies/{job['id']}/", copy['title'], copy['summary'], body,
                      languages=tuple(code for code in LOCALES if job.get(code)), schema=schema, noindex=not active)


def build(root, source, today):
    from site_catalog import catalog, saved
    from site_pages import HUBS, cases, contact, employers, home, hub, intake_page, wrap_editorial, write

    jobs = read_jobs(source)
    active = sorted((job for job in jobs if (job['status'] == 'external' and job['sourceChecked'] <= today)
                     or (job['status'] == 'published' and job['datePosted'] <= today <= job['validThrough'])),
                    key=lambda job: (-date.fromisoformat(listing_date(job)).toordinal(), job['id']))
    active_ids = {job['id'] for job in active}
    saved_jobs = active + [{**job, 'status': 'closed'} for job in jobs
                          if job['status'] in ('published', 'closed') and listing_date(job) <= today and job['id'] not in active_ids]
    generated = set()
    for lang in LOCALES:
        prefix = locale_path(lang)
        core = {'': home(lang, active), 'jobs/': catalog(lang, active), 'saved/': saved(lang, saved_jobs),
                'employers/': employers(lang), 'contact/': contact(lang), 'cases/': cases(lang),
                'apply/': intake_page(lang, 'apply'), 'submit-vacancy/': intake_page(lang, 'employer')}
        core.update({f'jobs/{slug}/': hub(lang, slug, active) for slug in HUBS})
        for route, html in core.items():
            write(root, lang, route, html)
        for job in jobs:
            if job['status'] == 'draft' or listing_date(job) > today or not job.get(lang):
                continue
            path = root / prefix / f'vacancies/{job["id"]}/index.html'
            write_page(path, vacancy_page(job, lang, job['id'] in active_ids))
            generated.add(path)
        for old in (root / prefix / 'vacancies').glob('*/index.html'):
            if old not in generated and MARKER in old.read_text(encoding='utf-8'):
                old.unlink()
        for directory in ('about', 'blog', 'candidates', 'employers', 'insights', 'jobs', 'locations', 'privacy', 'salary-guide'):
            for path in (root / prefix / directory).rglob('index.html'):
                route = path.relative_to(root / prefix).as_posix().removesuffix('index.html')
                if route in core:
                    continue
                original = path.read_text(encoding='utf-8')
                updated = wrap_editorial(original, lang, route)
                if updated != original:
                    path.write_text(updated, encoding='utf-8')

    sitemap = ET.Element(f'{{{NS}}}urlset')
    ET.register_namespace('', NS)
    for path in sorted(root.rglob('index.html')):
        relative = path.relative_to(root)
        if any(part.startswith(('.', 'demo-')) for part in relative.parts) or relative.parts[0] in ('www', 'downloads'):
            continue
        text = path.read_text(encoding='utf-8').split('</head>', 1)[0]
        if 'name="robots" content="noindex' in text:
            continue
        canonical = re.search(r'<link rel="canonical" href="([^"]+)"', text)
        if canonical is not None:
            node = ET.SubElement(sitemap, f'{{{NS}}}url')
            ET.SubElement(node, f'{{{NS}}}loc').text = canonical[1]
    tree = ET.ElementTree(sitemap)
    ET.indent(tree, space='  ')
    tree.write(root / 'sitemap.xml', encoding='utf-8', xml_declaration=True)
    print(f'Public site built: {len(active)} open vacancies, {len(generated)} vacancy pages.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT, help='Site checkout')
    parser.add_argument('--source', type=Path, help='Reviewed vacancy data outside the public site')
    args = parser.parse_args()
    try:
        build(args.root, args.source or args.root / 'content' / 'vacancies.json',
              datetime.now(KYIV).date().isoformat())
    except (ValueError, TypeError, OSError) as error:
        parser.exit(1, f'Catalog build failed: {error}\n')
